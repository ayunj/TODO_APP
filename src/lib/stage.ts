/**
 * 곰돌이가 방 안에서 서는 자리 — **한 군데에만 적는다.**
 *
 * ─── 왜 한 군데인가 ────────────────────────────────────────────
 *
 * 곰돌이가 방 위에 서는 자리가 넷이다. 홈 칸, 내 옷장의 걸쳐보는 칸, 세트 펼친 칸,
 * 그리고 [상점 채우기의 맞추는 칸](../screens/admin/Align.tsx).
 *
 * 이 값을 자리마다 따로 적어뒀다가 **어긋났다.** 상점에서 72%로 맞춰 올린 그림이
 * 홈에서는 92%로 서서 훨씬 컸다. 발주서에 이미 적혀 있던 줄을 어긴 것이다 —
 *
 * > **걸쳐보는 칸과 홈 칸은 같은 비율이어야 한다.**
 * > 걸쳐본 대로 홈에 서지 않으면 걸쳐보는 뜻이 없다.
 * > ([design/g/그릴-것.md](../../design/g/그릴-것.md))
 *
 * 그래서 여기 한 줄로 모았다. **고칠 일이 있으면 여기만 고친다.**
 *
 * ─── 왜 이 값인가 ──────────────────────────────────────────────
 *
 * 정사각 그림 안에 **머리 위 여백이 있다.** 곰토끼 귀나 마법사 고깔이 들어갈
 * 자리를 비워둔 것이라(`scripts/bears.mjs`의 `FIT`), 그만큼 칸을 키워야
 * 곰돌이가 제 크기로 선다.
 *
 * 여백을 174px에서 257px로 늘리면서 이 값도 72%에서 85%로 같이 키웠다 —
 * **화면에 뜨는 크기는 그대로다.** 여백이 없던 시절의 46%로 두면 절반만 하다.
 *
 * 그 뒤로 85 → 90 → 92%로 두 번 더 키웠다. 이번엔 여백 때문이 아니라
 * **곰돌이가 방에 견줘 작아 보여서**다.
 *
 * ─── 상한은 92%가 아니라 `BEAR_W + BEAR_FLOOR = 100`이다 ───────
 *
 * 곰돌이는 바닥에서 `BEAR_FLOOR`만큼 떠 있으니 **둘을 더한 것이 칸 높이**다.
 * 100을 넘으면 칸 위로 삐져나가는데, 칸이 잘라내는 자리라 **머리 끝이 소리 없이 깎인다.**
 * 그림 위쪽 34%는 곰토끼 귀와 마법사 고깔이 들어갈 자리라(맞추는 칸이 거기까지 담는다)
 * `기본 곰은 안 잘리니 괜찮다`가 안 통한다.
 *
 * 그래서 더 키우려면 **발을 그만큼 내려야 한다.** 92%로 키우면서 바닥을 9 → 8%로 내렸다 —
 * 발자리는 3px쯤 내려앉지만 러그 안이라 티가 안 난다.
 *
 * `max-h`도 같이 묶는다. **한쪽만 묶으면 그림 비가 바뀔 때 칸을 뚫는다.**
 */

/** 곰돌이가 칸 폭의 몇 %로 뜨나 */
export const BEAR_W = 92;
/**
 * 발끝이 칸 바닥에서 몇 % 떠 있나.
 *
 * **러그 가운데에 선다.** 6%로 두면 발이 러그 아래쪽 테두리에 걸쳐서
 * 방 앞에 나와 선 것처럼 보였다 — 곰돌이는 러그를 밟고 서 있어야 한다.
 *
 * `BEAR_W`와 더해 100이다. 한쪽을 키우면 **다른 쪽이 그만큼 내려온다.**
 */
export const BEAR_FLOOR = 8;

/**
 * 곰돌이 한 마리 — 방 위에 얹는다.
 *
 * **위의 두 값과 같은 값을 적는다.** `mb`는 `BEAR_FLOOR`, `max-w`는 `BEAR_W`다 —
 * 클래스 이름은 지어 쓸 수가 없어서(테일윈드가 훑어 담는다) 한 번 더 적는다.
 * 하나만 고치면 홈·상점과 맞추는 칸이 어긋난다.
 *
 * **`scripts/bears.mjs`의 `SLOT`이 이 값을 베껴 쓴다**(node에서는 이 파일을 못 읽는다).
 */
export const BEAR_ART = 'relative z-[1] mb-[8%] block h-auto max-h-[92%] w-auto max-w-[92%]';

/**
 * 격자 칸 안의 곰돌이 — **칸보다 크게 그려 위를 잘라낸다.**
 *
 * 그림 한 장은 정사각인데 **위쪽 34%가 비어 있다.** 모자와 귀가 들어갈 자리로
 * 비워둔 칸이라, 한 장을 통째로 칸에 맞추면 곰돌이가 칸의 3분의 2만 쓰고 위가 훵하다 —
 * 103px 칸에서는 그게 그대로 `작다`로 읽힌다.
 *
 * 그래서 112%로 키워 **아래를 맞춰 붙인다.** 발은 제자리에 두고 빈 위만 잘려 나간다.
 *
 * **작은 칸에서만 자른다.** 홈과 걸쳐보는 칸은 한 장이 다 보여야 하는 자리라
 * `BEAR_ART`를 그대로 쓴다 — 거기서 잘리면 걸쳐본 것과 다른 것이 홈에 선다.
 *
 * **사는 시트는 자른다.** 그 칸은 방금 누른 격자 칸을 그대로 키운 것이라
 * 같은 자로 그려야 크기가 안 어긋난다 ([BuySheet](../sheets/BuySheet.tsx)).
 *
 * **모자가 아주 높은 옷은 위가 아슬아슬하다.** 잘려 나가는 것은 위 12%다.
 * 여백을 꽉 채워 그린 옷이 올라오면 끝이 깎이니,
 * 더 키울 때는 **제일 높은 모자를 걸어놓고 눈으로 보고** 키운다.
 *
 * 상점 격자([StoreCard](../screens/store/StoreCard.tsx))와 상점 채우기의
 * 작은 그림([Thumb](../screens/admin/Thumb.tsx))이 **같은 것을 본다** —
 * 채우면서 본 칸이 상점에서 그대로 서야 왕복이 안 생긴다.
 *
 * 담는 칸에 `relative`가 있어야 한다.
 */
export const BEAR_CARD = 'absolute bottom-0 left-1/2 h-auto w-[112%] max-w-none -translate-x-1/2';

/** 방 한 장 — 칸을 꽉 채운다. **아래를 맞춰 자른다** */
export const ROOM_ART = 'absolute inset-0 h-full w-full object-cover object-bottom';

/**
 * 방과 곰돌이가 앉는 정사각 칸.
 *
 * 세로는 아래, 가로는 **가운데**다. `place-items-end` 한 낱말로 쓰면
 * 가로까지 끝으로 밀려서 곰돌이가 오른쪽 벽에 붙는다 — 둘을 갈라 적는다.
 */
export const ROOM_BOX =
  'relative grid aspect-square w-full items-end justify-items-center overflow-hidden';
