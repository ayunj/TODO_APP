/**
 * 조사 — 앞말 받침에 따라 갈리는 것들.
 *
 * `설거지가`는 되는데 `설거지통가`는 안 된다. 이름을 문장에 끼워 넣는 자리에서는
 * 이걸 안 재면 반드시 어색한 말이 나온다.
 *
 * **어지간하면 조사를 안 붙이는 쪽이 낫다** — `우리집과`처럼 붙여 쓰면
 * 받침 없는 이름이 `회사과`가 된다([지운 것](../screens/settings/TrashScreen.tsx)의 안내 문구가
 * 그래서 조사를 피해 쓴 말이다). 여기 있는 것은 **꼭 끼워 넣어야 하는 한 자리**를 위한 것이다.
 */

/**
 * 받침이 있으면 `이`, 없으면 `가`.
 *
 * 한글이 아닌 글자로 끝나면 `가`로 둔다 — 영어나 숫자의 받침은 읽는 소리로 갈려서
 * (`3`은 `삼이`, `milk`는 `밀크가`) 글자만 봐서는 알 수 없다.
 * 이 앱의 할 일 이름은 거의 한글이라 그쪽을 맞추고, 나머지는 덜 어색한 쪽으로 둔다.
 */
export function iga(word: string): string {
  const last = word.trim().slice(-1);
  if (!last) return '가';
  const code = last.charCodeAt(0);
  // 가(0xAC00) ~ 힣(0xD7A3). 28로 나눈 나머지가 0이면 받침이 없다.
  if (code < 0xac00 || code > 0xd7a3) return '가';
  return (code - 0xac00) % 28 === 0 ? '가' : '이';
}
