-- 2026-08-10 · 방을 고치는 건 연 사람만
--
-- 정책이 `방 사람이면 누구나 rooms를 고친다`로 열려 있었다.
-- 화면에서는 주인에게만 열어뒀지만 **정책이 안 막고 있었다** —
-- 손님이 방 이름·나누는 것·초대 코드를 직접 바꿀 수 있었다.
--
-- 두 번 돌려도 된다.
-- ═══════════════════════════════════════════════════════════════════

drop policy if exists "방 사람이 방 이름을 고친다" on rooms;
drop policy if exists "방은 연 사람이 고친다" on rooms;

create policy "방은 연 사람이 고친다" on rooms
  for update using (created_by = auth.uid());

-- 주인이 바뀌는 길(맡기고 나가기)과 코드 새로 만들기는 security definer 함수라
-- 이 정책에 막히지 않는다. 손님이 할 수 있는 일은 나가기 하나뿐이고,
-- 그건 room_members의 `내 자리만 내가 뺀다` 정책이 따로 맡는다.
